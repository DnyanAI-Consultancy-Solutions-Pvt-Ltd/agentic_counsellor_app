# 3. BACKGROUND EXCEL SPREADSHEET WRITER
# ==========================================
def extract_and_save_excel(agent_response_text: str) -> bool:
    """Parses structural tokens generated by the agent and outputs a clean Excel workbook."""
    lines = agent_response_text.strip().split('\n')
    rows = []
    
    # Captures clean rows from the agent's structural outputs
    pattern = re.compile(r'(?:\*\*|)\s*DATA_ROW\s*:\s*(?:\*\*|)\s*(.*)', re.IGNORECASE)
    
    for line in lines:
        match = pattern.search(line.strip())
        if match:
            clean_line = match.group(1).strip()
            parts = [p.strip() for p in clean_line.split('|')]
            if len(parts) >= 4:
                rows.append({
                    "College Code": parts[0],
                    "College Name": parts[1],
                    "Branch": parts[2],
                    "Reasoning Preference": parts[3]
                })
                
    if rows:
        df = pd.DataFrame(rows)
        df.drop_duplicates(subset=["College Code", "Branch"], inplace=True)
        df.columns = ["College Code", "College Name", "Branch", "Reasoning Preference"]
        df.to_excel(OUTPUT_PATH, index=False, engine='openpyxl')
        return True
    return False


