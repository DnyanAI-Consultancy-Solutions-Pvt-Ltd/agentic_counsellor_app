# 2. OPTIMIZED TOKEN-SAFE RAG TOOL
# ==========================================
async def retrieve_pdf_knowledge_chunks(query_keyword: str) -> str:
    """
    True Agentic RAG Tool: Broadly locates matched cutoff data segments, 
    but drops empty spaces and isolates target rows to maintain a strict low-token 
    payload that respects Groq free-tier TPM ceilings.
    """
    pdf_files = ["2023ENGG_CAP1_CutOff.pdf"]
    matched_lines = []
    
    search_token = str(query_keyword).strip().lower()
    
    # Vocabulary helper normalization inside the retrieval vector stream
    if "computer" in search_token or "cs" in search_token:
        search_token = "comput"
    elif "mechan" in search_token or "mech" in search_token:
        search_token = "mechan"
    elif "civil" in search_token:
        search_token = "civil"
    elif "it" == search_token or "information" in search_token:
        search_token = "information"

    for pdf_path in pdf_files:
        full_path = os.path.join(SCRIPT_DIR, pdf_path)
        if not os.path.exists(full_path):
            continue
            
        try:
            reader = PdfReader(full_path)
            current_college = "Unknown Institution"
            
            for page_num, page in enumerate(reader.pages):
                text = page.extract_text() or ""
                lines = text.split('\n')
                
                # Check if this entire structural block contains relevant context
                if search_token in text.lower():
                    buffer_lines = []
                    for line in lines:
                        line_clean = line.strip()
                        if not line_clean:
                            continue
                            
                        if re.search(r'^\d{4}\s*-', line_clean) or "Institute" in line_clean or "College" in line_clean:
                            current_college = line_clean
                        
                        # Only take data-carrying lines to compress token size drastically
                        if any(k in line_clean.upper() for k in ["STAGE", "OPEN", "OBC", "SC", "ST", "PWD", "MINORITY"]) or search_token in line_clean.lower():
                            buffer_lines.append(f"[{current_college}] {line_clean}")
                    
                    if buffer_lines:
                        matched_lines.append(
                            f"--- CONTENT SECTOR ({pdf_path} | Page: {page_num + 1}) ---\n" + 
                            "\n".join(buffer_lines)
                        )
        except Exception as e:
            return f"Error reading document vectors: {str(e)}"
            
    if not matched_lines:
        return f"No context entries matched the search token: '{search_token}'."
        
    # Join target content tightly (Limit payload block size to avoid going over 12k tokens)
    compressed_payload = "\n\n".join(matched_lines[:5])
    return compressed_payload[:25000] # Safe substring truncation as a final guardrail


